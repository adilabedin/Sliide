#!/usr/bin/env python3
"""Generates every platform asset that shows the Sliide logo mark from one geometry.

The mark is a rounded-stroke "S" drawn on the 108x108 adaptive-icon grid. From the constants below this script writes:
  - androidApp/src/main/res/drawable/ic_logo_mark.xml   (adaptive-icon foreground, monochrome layer and splash icon)
  - iosApp/iosApp/Assets.xcassets/LaunchLogo.imageset/  (launch-screen logo, 120 pt at @1x/@2x/@3x)
  - iosApp/iosApp/Assets.xcassets/AppIcon.appiconset/   (1024 px light, dark and tinted app icons)
and checks that the mark keeps at least 3:1 contrast against both splash backgrounds.

Dev-only; the generated files are committed. Requires Pillow (`pip install pillow`). Run from anywhere:
    python3 -I tools/brand/generate_brand_assets.py
"""

from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]

# Colours copied from core/designsystem/.../theme/Color.kt (the source of truth).
CHAMPAGNE = "D9BF86"  # ChampagneLight: the mark
MIDNIGHT = "1E2A4A"  # Midnight: light-mode splash and icon background
INK_900 = "0D0E12"  # Ink900: dark-mode splash background

VIEWPORT = 108.0
STROKE_WIDTH = 10.8
# The "S" as cubic Bezier segments (start, control 1, control 2, end) in viewport units.
SEGMENTS = [
    ((69.6, 36.6), (64.8, 30.6), (57.6, 29.4), (52.8, 29.4)),
    ((52.8, 29.4), (43.2, 29.4), (37.2, 34.2), (37.2, 41.4)),
    ((37.2, 41.4), (37.2, 49.8), (45.6, 52.2), (54.0, 54.6)),
    ((54.0, 54.6), (62.4, 57.0), (70.8, 59.4), (70.8, 67.8)),
    ((70.8, 67.8), (70.8, 75.0), (63.6, 78.6), (55.2, 78.6)),
    ((55.2, 78.6), (49.2, 78.6), (42.0, 77.4), (37.2, 71.4)),
]

LAUNCH_LOGO_POINTS = 120
APP_ICON_PIXELS = 1024
SUPERSAMPLE = 4


def rgba(hex_colour, alpha=255):
    return tuple(int(hex_colour[i : i + 2], 16) for i in (0, 2, 4)) + (alpha,)


def relative_luminance(hex_colour):
    channels = [int(hex_colour[i : i + 2], 16) / 255 for i in (0, 2, 4)]
    linear = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
    return 0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2]


def contrast(a, b):
    high, low = sorted((relative_luminance(a), relative_luminance(b)), reverse=True)
    return (high + 0.05) / (low + 0.05)


def fmt(value):
    return f"{value:g}"


def path_data():
    data = "M{},{}".format(*map(fmt, SEGMENTS[0][0]))
    for _, c1, c2, end in SEGMENTS:
        data += " C{},{} {},{} {},{}".format(*map(fmt, (*c1, *c2, *end)))
    return data


def sample_curve(steps_per_segment=800):
    points = []
    for p0, p1, p2, p3 in SEGMENTS:
        for i in range(steps_per_segment + 1):
            t = i / steps_per_segment
            a, b, c, d = (1 - t) ** 3, 3 * t * (1 - t) ** 2, 3 * t * t * (1 - t), t**3
            points.append(
                (
                    a * p0[0] + b * p1[0] + c * p2[0] + d * p3[0],
                    a * p0[1] + b * p1[1] + c * p2[1] + d * p3[1],
                ),
            )
    return points


def render(size, mark_colour, background=None, inset=0.0):
    """Renders the mark into a size x size image. `inset` crops that many viewport units from each edge."""
    canvas = size * SUPERSAMPLE
    scale = canvas / (VIEWPORT - 2 * inset)
    image = Image.new("RGBA", (canvas, canvas), background or (0, 0, 0, 0))
    draw = ImageDraw.Draw(image)
    radius = STROKE_WIDTH / 2 * scale
    # Stamping a round brush along the densely sampled curve gives round caps and smooth joins, matching Android's
    # vector stroke with strokeLineCap="round".
    for x, y in sample_curve():
        cx, cy = (x - inset) * scale, (y - inset) * scale
        draw.ellipse((cx - radius, cy - radius, cx + radius, cy + radius), fill=mark_colour)
    return image.resize((size, size), Image.LANCZOS)


def write_android_vector():
    target = ROOT / "androidApp/src/main/res/drawable/ic_logo_mark.xml"
    target.write_text(
        f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/brand/generate_brand_assets.py; edit the geometry there and regenerate. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="{fmt(VIEWPORT)}"
    android:viewportHeight="{fmt(VIEWPORT)}">
    <path
        android:pathData="{path_data()}"
        android:strokeWidth="{fmt(STROKE_WIDTH)}"
        android:strokeColor="@color/logo_mark"
        android:strokeLineCap="round"
        android:strokeLineJoin="round" />
</vector>
""",
    )
    return target


def write_launch_logo():
    folder = ROOT / "iosApp/iosApp/Assets.xcassets/LaunchLogo.imageset"
    folder.mkdir(parents=True, exist_ok=True)
    written = []
    for factor in (1, 2, 3):
        target = folder / f"launch-logo@{factor}x.png"
        render(LAUNCH_LOGO_POINTS * factor, rgba(CHAMPAGNE)).save(target)
        written.append(target)
    return written


def write_app_icons():
    folder = ROOT / "iosApp/iosApp/Assets.xcassets/AppIcon.appiconset"
    variants = {
        "app-icon-1024.png": render(APP_ICON_PIXELS, rgba(CHAMPAGNE), rgba(MIDNIGHT)).convert("RGB"),
        "app-icon-1024-dark.png": render(APP_ICON_PIXELS, rgba(CHAMPAGNE), rgba(INK_900)).convert("RGB"),
        # Tinted icons are a greyscale glyph on transparency; iOS applies the tint.
        "app-icon-1024-tinted.png": render(APP_ICON_PIXELS, (255, 255, 255, 255)),
    }
    written = []
    for name, image in variants.items():
        target = folder / name
        image.save(target)
        written.append(target)
    return written


def check_contrast():
    for name, background in (("Midnight", MIDNIGHT), ("Ink900", INK_900)):
        ratio = contrast(CHAMPAGNE, background)
        print(f"contrast champagne/{name}: {ratio:.2f}:1")
        if ratio < 3.0:
            raise SystemExit(f"Mark contrast against {name} is {ratio:.2f}:1, below the required 3:1")


def main():
    check_contrast()
    for path in [write_android_vector(), *write_launch_logo(), *write_app_icons()]:
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
