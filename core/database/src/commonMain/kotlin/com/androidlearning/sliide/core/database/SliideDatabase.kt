package com.androidlearning.sliide.core.database

import androidx.room.ConstructedBy
import androidx.room.Database
import androidx.room.RoomDatabase
import androidx.room.RoomDatabaseConstructor

@Database(
    entities = [UserEntity::class, PendingSyncEntity::class],
    version = 1,
)
@ConstructedBy(SliideDatabaseConstructor::class)
abstract class SliideDatabase : RoomDatabase() {
    abstract val userDao: UserDao
    abstract val pendingSyncDao: PendingSyncDao

    companion object {
        const val FILE_NAME = "sliide.db"
    }
}

/** Required by Room KMP; the `actual` for every target is generated by the Room KSP processor. */
@Suppress("KotlinNoActualForExpect")
expect object SliideDatabaseConstructor : RoomDatabaseConstructor<SliideDatabase> {
    override fun initialize(): SliideDatabase
}
